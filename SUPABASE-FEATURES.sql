-- جدولة النشر وإظهار/إخفاء المشاريع
alter table public.projects add column if not exists is_published boolean not null default true;
alter table public.projects add column if not exists publish_at timestamptz;

-- معرض صور متعدد لكل مشروع. project_id نص لتفادي افتراض نوع projects.id الحالي.
create table if not exists public.project_images (
  id bigint generated by default as identity primary key,
  project_id text not null,
  image_url text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
alter table public.project_images enable row level security;
drop policy if exists "Public can view gallery images" on public.project_images;
create policy "Public can view gallery images" on public.project_images for select to anon, authenticated using (
  exists (select 1 from public.projects p where p.id::text = project_id and coalesce(p.is_published,true) = true and (p.publish_at is null or p.publish_at <= now()))
  or exists (select 1 from public.site_admins where user_id = (select auth.uid()))
);
drop policy if exists "Admins can add gallery images" on public.project_images;
create policy "Admins can add gallery images" on public.project_images for insert to authenticated with check (
  exists (select 1 from public.site_admins where user_id = (select auth.uid()))
);
drop policy if exists "Admins can update gallery images" on public.project_images;
create policy "Admins can update gallery images" on public.project_images for update to authenticated using (
  exists (select 1 from public.site_admins where user_id = (select auth.uid()))
) with check (exists (select 1 from public.site_admins where user_id = (select auth.uid())));
drop policy if exists "Admins can delete gallery images" on public.project_images;
create policy "Admins can delete gallery images" on public.project_images for delete to authenticated using (
  exists (select 1 from public.site_admins where user_id = (select auth.uid()))
);

-- إعدادات الموقع القابلة للتحكم من الأدمن
create table if not exists public.site_settings (
  setting_key text primary key,
  setting_value text not null default '',
  updated_at timestamptz not null default now()
);
alter table public.site_settings enable row level security;
drop policy if exists "Public can read site settings" on public.site_settings;
create policy "Public can read site settings" on public.site_settings for select to anon, authenticated using (true);
drop policy if exists "Admins can manage site settings" on public.site_settings;
create policy "Admins can manage site settings" on public.site_settings for all to authenticated using (
  exists (select 1 from public.site_admins where user_id = (select auth.uid()))
) with check (exists (select 1 from public.site_admins where user_id = (select auth.uid())));

-- سجل تحديثات الموقع
create table if not exists public.site_updates (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null default '',
  created_at timestamptz not null default now(),
  is_published boolean not null default true
);
alter table public.site_updates enable row level security;
drop policy if exists "Public can view published updates" on public.site_updates;
create policy "Public can view published updates" on public.site_updates for select to anon, authenticated using (is_published = true);
drop policy if exists "Admins can manage updates" on public.site_updates;
create policy "Admins can manage updates" on public.site_updates for all to authenticated using (
  exists (select 1 from public.site_admins where user_id = (select auth.uid()))
) with check (exists (select 1 from public.site_admins where user_id = (select auth.uid())));

-- استطلاعات الرأي وتصويت الزوار
create table if not exists public.site_polls (
  id bigint generated by default as identity primary key,
  question text not null,
  options jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  is_active boolean not null default true
);
alter table public.site_polls enable row level security;
drop policy if exists "Public can view active polls" on public.site_polls;
create policy "Public can view active polls" on public.site_polls for select to anon, authenticated using (is_active = true);
drop policy if exists "Admins can manage polls" on public.site_polls;
create policy "Admins can manage polls" on public.site_polls for all to authenticated using (
  exists (select 1 from public.site_admins where user_id = (select auth.uid()))
) with check (exists (select 1 from public.site_admins where user_id = (select auth.uid())));
create table if not exists public.site_poll_votes (
  id bigint generated by default as identity primary key,
  poll_id bigint not null references public.site_polls(id) on delete cascade,
  option_index integer not null,
  voter_token text not null,
  created_at timestamptz not null default now(),
  unique (poll_id, voter_token)
);
alter table public.site_poll_votes enable row level security;
drop policy if exists "Public can submit poll votes" on public.site_poll_votes;
create policy "Public can submit poll votes" on public.site_poll_votes for insert to anon, authenticated with check (
  option_index >= 0 and exists (select 1 from public.site_polls where id = poll_id and is_active = true)
);
drop policy if exists "Public can read poll totals" on public.site_poll_votes;
create policy "Public can read poll totals" on public.site_poll_votes for select to anon, authenticated using (true);
drop policy if exists "Admins can manage poll votes" on public.site_poll_votes;
create policy "Admins can manage poll votes" on public.site_poll_votes for all to authenticated using (
  exists (select 1 from public.site_admins where user_id = (select auth.uid()))
) with check (exists (select 1 from public.site_admins where user_id = (select auth.uid())));

-- سياسة المشاريع: الزوار يرون المنشور فقط، والمديرون يرون الكل.
alter table public.projects enable row level security;
drop policy if exists "Public can view projects" on public.projects;
create policy "Public can view projects" on public.projects for select to anon, authenticated using (
  (coalesce(is_published,true) = true and (publish_at is null or publish_at <= now()))
  or exists (select 1 from public.site_admins where user_id = (select auth.uid()))
);
